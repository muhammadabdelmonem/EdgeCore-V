import numpy as np

# ── Load the trained weights ──────────────────────────────────────────────────
data = np.load("mnist_weights.npz")

W1 = data['W1']   # shape: (128, 784)
b1 = data['b1']   # shape: (128, 1)
W2 = data['W2']   # shape: (64,  128)
b2 = data['b2']   # shape: (64,  1)
W3 = data['W3']   # shape: (10,  64)
b3 = data['b3']   # shape: (10,  1)

print("Loaded weights:")
print(f"  W1: {W1.shape}  min={W1.min():.4f}  max={W1.max():.4f}")
print(f"  W2: {W2.shape}  min={W2.min():.4f}  max={W2.max():.4f}")
print(f"  W3: {W3.shape}  min={W3.min():.4f}  max={W3.max():.4f}")


# ── Quantization ──────────────────────────────────────────────────────────────
#
#  We want to store weights as int8 (integers from -127 to 127).
#
#  For each matrix:
#    1. Find the biggest absolute value  (e.g. 0.85)
#    2. Compute scale = 127 / max_abs    (e.g. 149.4)
#    3. Multiply every weight by scale, round, clip to [-127, 127]
#    4. Save the scale — the C code divides by it after each layer
#
#  Example:
#    float weight = 0.312
#    scale        = 149.4
#    int8 weight  = round(0.312 * 149.4) = 47
#
def quantize(arr, name):
    max_abs = np.max(np.abs(arr))
    scale   = 127.0 / max_abs
    q       = np.clip(np.round(arr * scale), -127, 127).astype(np.int8)
    print(f"\n  {name}:")
    print(f"    float range : [{arr.min():.4f}, {arr.max():.4f}]")
    print(f"    scale       : {scale:.4f}")
    print(f"    int8 range  : [{q.min()}, {q.max()}]")
    return q, scale

print("\nQuantizing...")
W1q, sW1 = quantize(W1, "W1")
b1q, sb1 = quantize(b1, "b1")
W2q, sW2 = quantize(W2, "W2")
b2q, sb2 = quantize(b2, "b2")
W3q, sW3 = quantize(W3, "W3")
b3q, sb3 = quantize(b3, "b3")


# ── Helper: write a flat C array ──────────────────────────────────────────────
def write_array(f, name, arr, cols=16):
    flat = arr.flatten()
    f.write(f"static const int8_t {name}[] = {{\n")
    for i in range(0, len(flat), cols):
        chunk = flat[i:i+cols]
        line  = ", ".join(f"{int(v):4d}" for v in chunk)
        f.write(f"    {line},\n")
    f.write("};\n\n")


# ── Write weights.h ───────────────────────────────────────────────────────────
with open("weights.h", "w") as f:

    f.write("// weights.h — auto-generated by export_weights.py\n")
    f.write("// Do not edit by hand.\n\n")
    f.write("#ifndef WEIGHTS_H\n")
    f.write("#define WEIGHTS_H\n\n")

    f.write("// Network dimensions\n")
    f.write("#define INPUT_SIZE   784\n")
    f.write("#define HIDDEN1_SIZE 128\n")
    f.write("#define HIDDEN2_SIZE  64\n")
    f.write("#define OUTPUT_SIZE   10\n\n")

    f.write("// Scale factors — divide accumulator by these after each layer\n")
    f.write(f"#define SCALE_W1 {sW1:.6f}f\n")
    f.write(f"#define SCALE_B1 {sb1:.6f}f\n")
    f.write(f"#define SCALE_W2 {sW2:.6f}f\n")
    f.write(f"#define SCALE_B2 {sb2:.6f}f\n")
    f.write(f"#define SCALE_W3 {sW3:.6f}f\n")
    f.write(f"#define SCALE_B3 {sb3:.6f}f\n\n")

    f.write("// W1[HIDDEN1_SIZE][INPUT_SIZE]  — access: W1_data[neuron * INPUT_SIZE + pixel]\n")
    write_array(f, "W1_data", W1q)

    f.write("// b1[HIDDEN1_SIZE]\n")
    write_array(f, "b1_data", b1q)

    f.write("// W2[HIDDEN2_SIZE][HIDDEN1_SIZE]\n")
    write_array(f, "W2_data", W2q)

    f.write("// b2[HIDDEN2_SIZE]\n")
    write_array(f, "b2_data", b2q)

    f.write("// W3[OUTPUT_SIZE][HIDDEN2_SIZE]\n")
    write_array(f, "W3_data", W3q)

    f.write("// b3[OUTPUT_SIZE]\n")
    write_array(f, "b3_data", b3q)

    f.write("#endif // WEIGHTS_H\n")

total = W1q.size + b1q.size + W2q.size + b2q.size + W3q.size + b3q.size
print(f"\nDone! weights.h written.")
print(f"  Total integers : {total:,}")
print(f"  Memory size    : ~{total/1024:.1f} KB  (each number = 1 byte)")